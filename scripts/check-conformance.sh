#!/usr/bin/env bash
#
# check-conformance.sh — the box and the apps must agree on the wire, byte for byte.
#
# The same formats are implemented more than once, and that is deliberate rather than
# accidental. The Bloom filter is written in Go for the box and in TypeScript for the
# scanner, because the scanner has to answer "is this ticket even real" with no
# network and cannot call the box to find out. The QR codecs exist on both sides for
# the same reason. Noise exists in Go and will exist in Kotlin and Swift.
#
# Every one of those pairs is a chance to disagree, and a disagreement does not look
# like a failing test — it looks like a gate that rejects a valid ticket at 21:00.
#
# So the fixtures are generated by Go and read by the TypeScript tests. When the Go
# side changes, the fixture changes, and the TypeScript test fails until it is fixed.
# This script asserts the fixture in the repository is the one the current Go code
# produces: a committed fixture that has drifted from the code it came from is worse
# than no fixture, because it makes both sides look like they agree.

set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")/.."

fail=0
say() { printf '\n\033[1m%s\033[0m\n' "$*"; }
bad() { printf '  \033[31m%s\033[0m\n' "$*"; fail=1; }
good() { printf '  \033[32m%s\033[0m\n' "$*"; }

say "the committed fixtures are what the Go code produces"

# The bloom fixture is regenerated and compared. The generator lives in the Go test
# behind GATECRASH_UPDATE_FIXTURES, which is the usual golden-file pattern and means
# the fixture cannot be produced by anything other than the code it is testing.
fixture="packages/protocol/test/testdata/bloom.json"
if [[ ! -f "$fixture" ]]; then
  bad "$fixture is missing, so the scanner's filter is unchecked against the box's"
else
  before="$(shasum -a 256 "$fixture" | cut -d' ' -f1)"
  GATECRASH_UPDATE_FIXTURES=1 go test ./internal/bloom/ -run Fixture >/dev/null
  after="$(shasum -a 256 "$fixture" | cut -d' ' -f1)"
  if [[ "$before" != "$after" ]]; then
    bad "$fixture is stale — regenerated it and the bytes changed"
    bad "commit the regenerated file, and expect the TypeScript test to fail until it is updated"
  else
    good "$fixture matches the current Go implementation"
  fi
fi

say "the TypeScript side reads them"

# Run only the tests that consume a fixture. A full pnpm test run happens elsewhere in
# CI; the point here is to make the failure legible when it is specifically a
# cross-language disagreement rather than a broken app.
if ! pnpm --filter gatecrash-client exec vitest run test/bloom.test.ts test/qr.test.ts; then
  bad "the TypeScript implementation disagrees with the Go one"
else
  good "the TypeScript codecs agree with the fixtures"
fi

say "the wire constants match on both sides"

# A handful of numbers that appear in two languages and have to be identical. Checked
# by grep rather than by generating a shared header, because generating one for six
# constants is more machinery than the problem deserves — and a mismatch here is
# exactly the sort of thing that is invisible until a phone meets a box.
check_constant() {
  local name="$1" go_pattern="$2" ts_pattern="$3"
  local go_value ts_value
  go_value="$(grep -rhoE "$go_pattern" internal packages 2>/dev/null | head -1 | grep -oE '[0-9]+' | head -1 || true)"
  ts_value="$(grep -rhoE "$ts_pattern" packages 2>/dev/null | head -1 | grep -oE '[0-9]+' | head -1 || true)"

  if [[ -z "$go_value" || -z "$ts_value" ]]; then
    printf '  %-28s not found on both sides, skipping\n' "$name"
    return
  fi
  if [[ "$go_value" != "$ts_value" ]]; then
    bad "$name: Go says $go_value, TypeScript says $ts_value"
  else
    good "$name = $go_value"
  fi
}

check_constant "GC2 window (seconds)" 'WindowSeconds\s*=\s*[0-9]+' 'WINDOW_SECONDS\s*=\s*[0-9]+'
check_constant "ticket id bytes" 'IDLen\s*=\s*[0-9]+' 'ID_BYTES\s*=\s*[0-9]+'
check_constant "ticket id characters" 'EncodedIDLen\s*=\s*[0-9]+' 'ID_CHARS\s*=\s*[0-9]+'

# GC1Len is computed from its parts in Go rather than written as a literal, so grep
# cannot reach it. It is tied to the TypeScript constant by
# TestGC1LengthMatchesTheClients instead, which is the better place for it: the test
# fails with the name of the file to change.

# The window tolerance is deliberately not compared. The box enforces it and the apps
# never need to: a phone generates a code for the current window, and the box decides
# what drift it accepts. If a client ever starts making that judgement, this is where
# the two values have to be tied together.

if [[ $fail -ne 0 ]]; then
  printf '\n\033[31mconformance failed\033[0m\n\n'
  exit 1
fi

printf '\n\033[32mthe box and the apps agree\033[0m\n\n'
